// THE NIGHTLY FACELESS EXPLAINER (run from cron at ~3:40, after the digest). Topic → sourced
// script → ElevenLabs voice (Flash, budget-capped) → Opus builds bespoke 3D scenes on the
// explainer kit → it renders stills and fixes what it sees → full render → staged in Telegram
// with [Post] (via the bot's trigger inbox). It never posts by itself. Any failure = a message.
//   npx tsx src/jobs/explainer.ts            (the real run)
//   npx tsx src/jobs/explainer.ts --topic "…" (force a topic)
//   npx tsx src/jobs/explainer.ts --reuse duo --dry
//     (test the scene builder + render on an existing script/voice: no credits, nothing staged)

const STUDIO = config.studioDir;
const GEN = resolve(STUDIO, "src/explainer/gen");
const HISTORY = resolve(REPO_ROOT, "bot/data/explainers.jsonl");
const LOCK = resolve(REPO_ROOT, "bot/data/explainer.lock");
const VOICE_ID = "nPczCjzI2devNBz1zQrb"; // "Brian" (sahil approved)
const MODEL = "eleven_flash_v2_5";
// the runner has no GPU: Mesa's Vulkan (lavapipe) measured ~0.4 s/frame for the 3D, 2x SwiftShader;
// "angle-egl" can't create a WebGL context in Remotion's headless shell there
const GL = process.platform === "linux" ? ["--gl=vulkan"] : ["--gl=angle"];
const BUILD_TOOLS = ["Read", "Write", "Edit", "Glob", "Grep", "Bash(npx tsc:*)", "Bash(npx remotion still:*)"];

type Script = { id: string; title: string; coverTitle?: string; topic: string; lines: { scene: string; text: string }[]; sources: string[]; facts: string; caption: string };

function run(cmd: string, args: string[], cwd = STUDIO, timeoutMs = 30 * 60_000): Promise<{ ok: boolean; out: string }> {
  return new Promise((res) => {
    const p = spawn(cmd, args, { cwd, shell: process.platform === "win32" });
    let out = "";
    const t = setTimeout(() => p.kill("SIGKILL"), timeoutMs);
    p.stdout.on("data", (d) => (out += d));
    p.stderr.on("data", (d) => (out += d));
    p.on("error", (e) => res({ ok: false, out: String(e) }));
    p.on("close", (code) => {
      clearTimeout(t);
      res({ ok: code === 0, out: out.slice(-2000) });
    });
  });
}
async function ffmpeg(args: string[]) {
  const sys = await run("ffmpeg", ["-hide_banner", "-loglevel", "error", ...args]);
  return sys.ok ? sys : run("npx", ["remotion", "ffmpeg", "-hide_banner", "-loglevel", "error", ...args]);
}
const log = (m: string) => console.log(`[explainer ${new Date().toISOString().slice(11, 19)}] ${m}`);

/** the registry Root.tsx renders compositions from: every folder in gen/ with a Video.tsx */
export async function writeRegistry() {
  await mkdir(GEN, { recursive: true });
  const ids = readdirSync(GEN, { withFileTypes: true }).filter((d) => d.isDirectory() && existsSync(resolve(GEN, d.name, "Video.tsx"))).map((d) => d.name).sort();
  const v = (id: string) => id.replace(/[^a-zA-Z0-9]/g, "_");
  const src = [
    "// generated by bot/src/jobs/explainer.ts: one entry per folder with a Video.tsx. Do not edit.",
    'import type React from "react";',
    ...ids.map((id) => `import V_${v(id)}, { FRAMES as F_${v(id)} } from "./${id}/Video";`),
    "export const GENERATED_EXPLAINERS: { id: string; component: React.FC; frames: number }[] = [",
    ...ids.map((id) => `  { id: "${id}", component: V_${v(id)}, frames: F_${v(id)} },`),
    "];",
    "",
  ].join("\n");
  await writeFile(resolve(GEN, "index.ts"), src);
}

async function tsc(): Promise<{ ok: boolean; errors: string }> {
  const r = await run("npx", ["tsc", "--noEmit"], STUDIO, 5 * 60_000);
  return { ok: r.ok, errors: r.out.slice(-3000) };
}

// keep the newest few generated videos; the rest only slow the bundle down
function prune(keep = 4) {
  if (!existsSync(GEN)) return;
  const dirs = readdirSync(GEN, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort();
  for (const d of dirs.slice(0, Math.max(0, dirs.length - keep))) rmSync(resolve(GEN, d), { recursive: true, force: true });
}

async function history(): Promise<string[]> {
  try {
    return (await readFile(HISTORY, "utf8")).trim().split("\n").filter(Boolean).map((l) => JSON.parse(l).topic as string);
  } catch {
    return [];
  }
}

async function writeAndVoice(guide: string, stamp: string, forcedTopic?: string): Promise<{ script: Script; timed: Timed; credits: number }> {
  const done = await history();
  const { used } = await creditsUsedThisMonth();
  if (used + 450 > monthlyCap()) throw new BudgetError(`ElevenLabs: ${used}/${monthlyCap()} credits used this month, not enough left for tonight's explainer.`);

  // 1. topic + script
  log("researching + writing");
  const script = await claudeJson<Script>(
    `${guide}

You are tonight's writer for this series. ${forcedTopic ? `TOPIC (sahil picked it): ${forcedTopic}` : `Find what's trending this week (search the news and the AI/tech conversation from the last 7 days) and pick the ONE topic with the best mix of mainstream curiosity, a mechanism worth explaining, and something animatable in 3D.`}
Already done (don't repeat): ${done.slice(-30).join(" | ") || "nothing yet besides the iPhone Duo cracking video"}.
Fetch your sources (WebSearch, WebFetch) and only write what they support.

Return JSON:
{"id":"short-kebab-slug-${stamp}","title":"the video's title","coverTitle":"the cover's title: 4-8 words, the hook, the key words in *asterisks* (e.g. Why the iPhone Duo is *already cracking*)","topic":"one line: what it's about",
 "lines":[{"scene":"hook","text":"…*emphasis*…"}, … 8-10 lines, each scene a short unique key …],
 "sources":["urls you used"],
 "facts":"a dense paragraph of the verified facts behind every line, with the source for each (this is what the site article is written from)",
 "caption":"the Instagram caption per the guide"}`,
    { tools: ["WebSearch", "WebFetch"], timeoutMs: 15 * 60_000 },
  );
  script.id = (script.id || `explainer-${stamp}`).toLowerCase().replace(/[^a-z0-9-]/g, "-").slice(0, 48);
  const words = script.lines.map((l) => l.text).join(" ").split(/\s+/).length;
  if (script.lines.length < 6 || words > 160) throw new Error(`script out of bounds (${script.lines.length} lines, ${words} words)`);
  log(`"${script.title}" (${words} words)`);

  // 2. voice → normalised, fitted to ≤50 s
  const pub = resolve(STUDIO, "public/explainer", script.id);
  await mkdir(pub, { recursive: true });
  await writeFile(resolve(pub, "script.json"), JSON.stringify(script, null, 2));
  const plain = script.lines.map((l) => l.text.replace(/\*/g, "")).join(" ");
  const v = await tts(plain, resolve(pub, "voice.mp3"), { voiceId: VOICE_ID, model: MODEL, settings: { stability: 0.42, similarity_boost: 0.8, style: 0.3, use_speaker_boost: true } });
  const tempo = Math.min(1.08, Math.max(1, v.durationMs / 49_500));
  const norm = await ffmpeg(["-y", "-i", resolve(pub, "voice.mp3"), "-af", `loudnorm=I=-15:TP=-1.5:LRA=11${tempo > 1.001 ? `,atempo=${tempo.toFixed(3)}` : ""}`, "-ar", "44100", "-b:a", "192k", resolve(pub, "voice-norm.mp3")]);
  if (!norm.ok) throw new Error(`voice normalise failed: ${norm.out.slice(-200)}`);
  const timed = v.words.map((w) => ({ ...w, startMs: Math.round(w.startMs / tempo), endMs: Math.round(w.endMs / tempo) }));
  log(`voice ${(v.durationMs / 1000).toFixed(1)} s → ${(timed[timed.length - 1].endMs / 1000).toFixed(1)} s, ${v.credits} credits`);
  return { script, timed, credits: v.credits };
}

// test mode: an existing script + voice (public/explainer/<src>/script.json, words.json, voice-norm.mp3)
async function reuse(src: string, stamp: string): Promise<{ script: Script; timed: Timed; credits: number }> {
  const from = resolve(STUDIO, "public/explainer", src);
  const script = JSON.parse(await readFile(resolve(from, "script.json"), "utf8")) as Script;
  const timed = JSON.parse(await readFile(resolve(from, "words.json"), "utf8")) as Timed;
  script.id = `${src}-rebuild-${stamp}`.toLowerCase().replace(/[^a-z0-9-]/g, "-");
  script.facts ??= "";
  script.caption ??= "";
  const pub = resolve(STUDIO, "public/explainer", script.id);
  await mkdir(pub, { recursive: true });
  await copyFile(resolve(from, "voice-norm.mp3"), resolve(pub, "voice-norm.mp3"));
  log(`reusing "${script.title}" from ${src} (no credits)`);
  return { script, timed, credits: 0 };
}

type Opts = { topic?: string; reuse?: string; dry?: boolean };
type Timed = { text: string; startMs: number; endMs: number }[];

export async function makeExplainer(opts: Opts = {}): Promise<string> {
  const guide = await readFile(resolve(REPO_ROOT, "EXPLAINER.md"), "utf8");
  const stamp = new Date().toISOString().slice(0, 10).replace(/-/g, "");
  const { script, timed, credits } = opts.reuse ? await reuse(opts.reuse, stamp) : await writeAndVoice(guide, stamp, opts.topic);
  const plain = script.lines.map((l) => l.text.replace(/\*/g, "")).join(" ");

  // 3. data file for the scenes
  const dir = resolve(GEN, script.id);
  await mkdir(dir, { recursive: true });
  await writeFile(
    resolve(dir, "data.ts"),
    `// generated: the script + ElevenLabs word timings for "${script.title}"\nimport type { Line, Word } from "../../kit";\nexport const lines: Line[] = ${JSON.stringify(script.lines.map((l) => ({ scene: l.scene, text: l.text })), null, 1)};\nexport const words: Word[] = ${JSON.stringify(timed)};\nexport const VOICE = "explainer/${script.id}/voice-norm.mp3";\n`,
  );

  // 4. Opus builds the scenes, renders stills, looks, fixes
  const comp = `Explainer-${script.id}`;
  log("building scenes");
  await claude(
    `${guide}

You are building tonight's video in this Remotion studio (cwd = studio/). The script, sources and
verified facts: ${JSON.stringify({ title: script.title, lines: script.lines, facts: script.facts })}
The narration is done: src/explainer/gen/${script.id}/data.ts exports lines, words (ms timings) and
VOICE (the audio path for staticFile).

Do this:
1. Read src/explainer/kit.tsx and the reference video src/explainer/duo/ (Duo.tsx, Phone.tsx,
   Stack.tsx, Hinge.tsx) closely. Reuse their patterns: per-scene ThreeCanvas shots with camAt
   keys + drift, Fade crossfades between shots, at(scene, word) timing, Captions/Counter/Note/
   Leader/project/Glow, the audio block (voice + a music bed from public/music at ~0.07 with
   bedCurve, whooshes on cuts, a click on each counter step).
2. Write src/explainer/gen/${script.id}/Video.tsx (+ any helper files in that folder ONLY) with a
   DEFAULT export React.FC (no props) and \`export const FRAMES\` = last word end + 40 frames at 30 fps.
   Do not edit any other file; the composition is registered automatically as "${comp}".
3. Design 2-4 3D "sets" that SHOW the mechanism the narration describes, beat by beat, with the
   objects in the middle band and labels pinned to them. Make it look like a premium explainer, not
   a slideshow: real-looking materials, the gold for the invisible physics, the x-ray look for
   internals, slow camera moves that push in on what's being said.
4. \`npx tsc --noEmit\` until it's clean.
5. Look at it: for each line, render a still at its middle frame:
   \`npx remotion still ${comp} out/${script.id}-f<frame>.png --frame=<frame> --scale=0.5 ${GL.join(" ")}\`
   Read every still. Fix: empty or black frames, objects off-screen or under the captions,
   labels pointing at nothing or overlapping, unreadable text, a scene that doesn't show what's
   being said. Re-render the ones you changed. Up to three passes.
${opts.reuse ? "This is a rebuild test of an existing script: design NEW scenes in your folder; don't import from src/explainer/duo/ (read it for patterns only).\n" : ""}Reply DONE when the stills look right.`,
    { tools: BUILD_TOOLS, cwd: STUDIO, timeoutMs: 55 * 60_000 },
  );
  await writeRegistry();
  let check = await tsc();
  if (!check.ok) {
    await claude(`The studio fails typecheck after you built src/explainer/gen/${script.id}/. Fix ONLY files in that folder:\n${check.errors}\nReply DONE.`, { tools: BUILD_TOOLS, cwd: STUDIO, timeoutMs: 10 * 60_000 });
    check = await tsc();
  }
  if (!check.ok || !existsSync(resolve(dir, "Video.tsx"))) {
    rmSync(dir, { recursive: true, force: true }); // never leave the studio broken for tomorrow's reels
    await writeRegistry();
    throw new Error(`the scenes didn't typecheck: ${check.errors.slice(-400)}`);
  }

  // 5. render (after any tool-reel render is done; never two at once)
  for (let i = 0; i < 60; i++) {
    const busy = await run("pgrep", ["-f", "remotion render"], STUDIO, 10_000);
    if (!busy.ok || process.platform === "win32") break;
    await new Promise((r) => setTimeout(r, 60_000));
  }
  log("rendering");
  const outDir = resolve(STUDIO, "out/explainer");
  await mkdir(outDir, { recursive: true });
  const mp4 = resolve(outDir, `${script.id}.mp4`);
  const r = await run("npx", ["remotion", "render", comp, mp4, ...GL, "--concurrency=2", "--crf=21"], STUDIO, 150 * 60_000);
  if (!r.ok || !existsSync(mp4)) throw new Error(`render failed: ${r.out.slice(-400)}`);
  // the cover: the series design (studio ExplainerCover) over the frame where the hook lands
  const cover = resolve(outDir, `${script.id}-cover.jpg`);
  const hookEnd = Math.round(((timed[Math.min(timed.length - 1, script.lines[0].text.split(/\s+/).length - 1)].endMs) / 1000) * 30);
  const frameRel = `explainer/${script.id}/cover-frame.png`;
  await run("npx", ["remotion", "still", comp, resolve(STUDIO, "public", frameRel), `--frame=${Math.max(10, hookEnd)}`, ...GL], STUDIO, 10 * 60_000);
  const coverProps = resolve(outDir, `${script.id}-cover.props.json`);
  await writeFile(coverProps, JSON.stringify({ title: script.coverTitle || script.title, image: frameRel }));
  await run("npx", ["remotion", "still", "ExplainerCover", cover, `--props=${coverProps}`, "--image-format=jpeg", "--jpeg-quality=92"], STUDIO, 10 * 60_000);

  if (opts.dry) {
    log(`dry run: ${mp4}${existsSync(cover) ? ` + ${cover}` : ""} (not staged)`);
    return script.title;
  }

  // 6. stage it in Telegram (the bot shows it with [Post] / [Redo] / [Edit])
  const pending = {
    topic: script.title,
    script: plain,
    postType: "news",
    aiGenerated: true,
    kind: "explainer",
    mp4Path: mp4,
    ...(existsSync(cover) ? { thumbPath: cover } : {}),
    caption: script.caption,
    context: `${script.facts}\nSources: ${script.sources.join(" ")}`,
  };
  const pendingPath = resolve(outDir, `${script.id}-pending.json`);
  await writeFile(pendingPath, JSON.stringify(pending, null, 1));
  await mkdir(resolve(REPO_ROOT, "bot/data/trigger"), { recursive: true });
  await writeFile(resolve(REPO_ROOT, "bot/data/trigger", `x-stage-${Date.now()}.txt`), `stage ${pendingPath}`);
  await appendFile(HISTORY, JSON.stringify({ at: new Date().toISOString(), id: script.id, topic: script.title, credits }) + "\n");
  prune();
  await writeRegistry();
  return script.title;
}

// CLI
if (process.argv[1] && /explainer\.(ts|js)$/.test(process.argv[1])) {
  const arg = (k: string) => {
    const i = process.argv.indexOf(k);
    return i > 0 ? process.argv[i + 1] : undefined;
  };
  const opts: Opts = { topic: arg("--topic"), reuse: arg("--reuse"), dry: process.argv.includes("--dry") };
  if (existsSync(LOCK)) {
    console.log("explainer already running (lock present)");
    process.exit(0);
  }
  await writeFile(LOCK, String(process.pid));
  try {
    const t0 = Date.now();
    const title = await makeExplainer(opts);
    log(`done in ${Math.round((Date.now() - t0) / 60000)} min: ${title}`);
  } catch (e: any) {
    const msg = String(e?.message ?? e);
    console.error("explainer failed:", msg);
    const why = e instanceof BudgetError ? msg : e instanceof ClaudeAuthError ? msg : `tonight's explainer didn't make it: ${msg.slice(0, 300)}`;
    if (!opts.dry) await sendToChat(`🎬 ${why}`).catch(() => {});
  } finally {
    rmSync(LOCK, { force: true });
  }
  process.exit(0);
}
